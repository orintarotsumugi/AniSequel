package com.anisequel.data.security

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import java.util.Base64
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Encrypts the AniList bearer token at rest.
 *
 * ## Why the token needs this
 *
 * A plaintext token in DataStore is a bearer credential for the reader's whole
 * AniList account: it can read their list, rewrite their progress and post as
 * them. Anything that can read the app's private data directory - a rooted
 * device, a bug in another process's file access, ADB on a debuggable build -
 * could lift it without ever knowing the password. The token now lives inside an
 * AES/GCM envelope whose key never leaves the Android keystore.
 *
 * ## Why a keystore key rather than a key derived from a password
 *
 * There is no password to derive one from, and asking for one would make the
 * app unusable for the people it is for. The keystore's `AndroidKeyStore`
 * provider is hardware-backed where the device supports it, is never exported,
 * and is invalidated if the device's secure lock is removed - which is exactly
 * the behaviour a stolen-then-reset phone needs.
 *
 * ## The invalidation case is not a crash
 *
 * Removing the screen lock (or restoring a backup onto new hardware) can
 * invalidate the key. Decryption then throws, and this class answers `null`.
 * [com.anisequel.data.repository.AuthRepositoryImpl] treats that as "no usable
 * session" and clears the unreadable ciphertext, so the app opens on the sign-in
 * screen instead of crashing on every launch. Re-authenticating is the only
 * correct recovery; the old token is unrecoverable by design.
 */
interface TokenCipher {
    /** Encrypts [plaintext] into a self-contained, storable string. */
    fun encrypt(plaintext: String): String

    /** Decrypts [payload], or null when it cannot be read by this device/key. */
    fun decrypt(payload: String): String?
}

/**
 * AES-256-GCM under a non-exportable `AndroidKeyStore` key.
 *
 * The stored form is `base64(iv):base64(ciphertext)`. The IV is generated by the
 * cipher for every encryption and must be stored beside the ciphertext - GCM
 * fails loudly if it is reused, which is the behaviour that makes the format
 * safe to rewrite on every sign-in.
 */
class KeystoreTokenCipher : TokenCipher {

    override fun encrypt(plaintext: String): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key())
        val iv = cipher.iv
        val encrypted = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))
        return "${encode(iv)}:${encode(encrypted)}"
    }

    override fun decrypt(payload: String): String? = runCatching {
        val separator = payload.indexOf(':')
        if (separator <= 0) return@runCatching null

        val iv = decode(payload.substring(0, separator))
        val encrypted = decode(payload.substring(separator + 1))
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(TAG_BITS, iv))
        String(cipher.doFinal(encrypted), Charsets.UTF_8)
    }.getOrElse {
        // The key was invalidated or the ciphertext was tampered with. Delete the
        // unusable key so the next save creates a fresh one rather than failing
        // on every write for the rest of the install's life.
        forgetKey()
        null
    }

    private fun key(): SecretKey {
        val store = keyStore()
        (store.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry)?.let { return it.secretKey }

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(KEY_SIZE_BITS)
                .build()
        )
        return generator.generateKey()
    }

    private fun keyStore(): KeyStore =
        KeyStore.getInstance(KEYSTORE).apply { load(null) }

    private fun forgetKey() {
        runCatching { keyStore().deleteEntry(KEY_ALIAS) }
    }

    private fun encode(bytes: ByteArray): String =
        Base64.getEncoder().encodeToString(bytes)

    private fun decode(value: String): ByteArray =
        Base64.getDecoder().decode(value)

    private companion object {
        const val KEYSTORE = "AndroidKeyStore"
        const val KEY_ALIAS = "anisequel_access_token"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val KEY_SIZE_BITS = 256
        const val TAG_BITS = 128
    }
}
